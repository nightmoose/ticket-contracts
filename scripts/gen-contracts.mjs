// Embed contracts/*.yaml into src/contracts.generated.ts so Forge functions can load them
// without filesystem access. Run: npm run gen:contracts (CI checks the output is up to date).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../contracts/', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.yaml')).sort();
let out = '// Generated by scripts/gen-contracts.mjs from contracts/*.yaml. Do not edit.\n';
out += 'export const CONTRACTS: Record<string, string> = {\n';
for (const f of files) out += `  ${JSON.stringify(f.replace(/\.yaml$/, ''))}: ${JSON.stringify(readFileSync(new URL(f, dir), 'utf8'))},\n`;
out += '};\n';
writeFileSync(new URL('../src/contracts.generated.ts', import.meta.url), out);
console.log(`wrote ${files.length} contract(s)`);
